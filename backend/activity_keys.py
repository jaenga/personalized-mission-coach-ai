def _compact(value: str) -> str:
    return "".join((value or "").split()).lower()


def normalize_activity_key(value: str | None) -> str | None:
    raw = (value or "").strip()
    if not raw:
        return None
    if raw in VALID_ACTIVITY_KEYS:
        return raw

    compact = _compact(raw)
    for key in VALID_ACTIVITY_KEYS:
        if _compact(key) == compact:
            return key

    alias = ACTIVITY_KEY_ALIASES.get(raw) or ACTIVITY_KEY_ALIASES.get(compact)
    if alias in VALID_ACTIVITY_KEYS:
        return alias
    return None


def is_valid_activity_key(value: str | None) -> bool:
    return normalize_activity_key(value) is not None
