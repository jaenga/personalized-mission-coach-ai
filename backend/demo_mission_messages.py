def attach_mission_message(mission: dict | None) -> dict | None:
    if not mission:
        return mission

    enriched = dict(mission)
    mission_id = enriched.get("mission_id")
    mission_name = enriched.get("mission_name") or "오늘의 미션"
    enriched["mission_message"] = DEMO_MISSION_MESSAGES.get(
        mission_id,
        f"오늘 미션은 ‘{mission_name}’이야! 한번 도전해보자!",
    )
    return enriched
