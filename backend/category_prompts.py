# ── 카테고리 프롬프트 호출 ───────────────────────────────────────────────────────────

def get_category_equivalency_prompt(
    main_category: str | None,
    sub_category: str | None,
) -> str:
    main_rule = MAIN_CATEGORY_RULES.get(main_category or "", "")
    sub_rule = SUB_CATEGORY_RULES.get(sub_category or "", "")

    return "\n\n".join(
        part
        for part in [
            COMMON_EQUIVALENCY_RULE,
            main_rule,
            sub_rule,
        ]
        if part
    )